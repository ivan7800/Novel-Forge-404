import assert from 'node:assert/strict';
import {validateSnapshot,upgradeSnapshot,renamedSnapshot,remapLore,wordCount} from '../src/model.js';
const project={id:'p',title:'Novela'};
const chapter={id:'c',projectId:'p',title:'Capítulo',content:'Uno'};
const scene={id:'s',projectId:'p',chapterId:'c',title:'Escena',content:'Dos'};
const legacy={app:'STORYVERSE-404',version:1,projects:[project],chapters:[chapter],scenes:[scene]};
assert.equal(validateSnapshot(legacy),true);
const upgraded=upgradeSnapshot(legacy);
assert.deepEqual(upgraded.characters,[]);
assert.equal(upgraded.links.length,0);
const modern={...upgraded,characters:[{id:'ch',projectId:'p',name:'Bruna'}],places:[{id:'pl',projectId:'p',name:'Cementerio'}],links:[{id:'l',projectId:'p',sourceType:'character',sourceId:'ch',targetType:'scene',targetId:'s'}]};
assert.equal(validateSnapshot(modern),true);
const remapped=renamedSnapshot(modern,new Set(['Novela']));
remapLore(modern,remapped);
assert.notEqual(remapped.projects[0].id,project.id);
assert.equal(remapped.projects[0].title,'Novela (importada)');
assert.equal(remapped.links[0].sourceId,remapped.characters[0].id);
assert.equal(remapped.links[0].targetId,remapped.scenes[0].id);
assert.equal(validateSnapshot(remapped),true);
assert.throws(()=>upgradeSnapshot({...legacy,scenes:[{...scene,chapterId:'missing'}]}),/Escena sin capítulo/);
assert.throws(()=>upgradeSnapshot({...modern,links:[{...modern.links[0],targetId:'missing'}]}),/Vínculo huérfano/);
assert.equal(wordCount('Uno dos tres'),3);
console.log('OK: validación, migración, remapeo de fichas y vínculos, rechazo de datos corruptos');
